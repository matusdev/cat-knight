export function tr(key, vars) {
  var s = (DICT[lang] && DICT[lang][key]) || RU[key] || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? vars[k] : m; });
  return s;
}

export function getLang() { return lang; }

export function setLang(l) {
  if (DICT[l]) lang = l;
  document.documentElement.lang = lang;
  applyDom();
}

export function applyDom(root) {
  (root || document).querySelectorAll('[data-i18n],[data-i18n-html],[data-i18n-label]').forEach(function (n) {
    if (n.dataset.i18n) n.textContent = tr(n.dataset.i18n);
    if (n.dataset.i18nHtml) n.innerHTML = tr(n.dataset.i18nHtml);
    if (n.dataset.i18nLabel) n.setAttribute('aria-label', tr(n.dataset.i18nLabel));
  });
}

// русское множественное: plural(5, ['монета', 'монеты', 'монет']); в английском — одна форма или две
export function plural(n, forms) {
  if (lang !== 'ru') return n === 1 ? forms[0] : forms[forms.length > 1 ? 1 : 0];
  var a = n % 10, b = n % 100;
  return a === 1 && b !== 11 ? forms[0] : a >= 2 && a <= 4 && (b < 12 || b > 14) ? forms[1] : forms[2];
}

